function Frame4Visual() {
  const reduce = useReducedMotion();
  // Per Frame 4 discipline: animate one branch at a time, REWRITE gets the
  // longest beat (~0.9s vs ~0.6s for the others), full color only on the
  // active branch, gray ghost outlines for the rest. Cycle order puts
  // REWRITE second so the visitor's brain pivots from "okay, normal flow"
  // to "wait, what did it just do?" within the first 1.5 seconds.
  const order = [0, 1, 2, 3, 4, 5]; // EXECUTE, REWRITE, REFUSE, DEFER, ESCALATE, REQUEST_CONFIRMATION
  return (
    <div className="grid w-full max-w-md gap-2 md:grid-cols-2">
      {order.map((idx, i) => {
        const branch = DECISION_BRANCHES[idx]!;
        const isRewrite = branch.kind === "REWRITE";
        // Stagger the highlight beats. REWRITE gets a longer dwell.
        const beat = i * 0.6 + (i > 1 ? 0.3 : 0); // shift later beats by REWRITE's extra dwell
        const dwell = isRewrite ? 0.9 : 0.6;
        return (
          <motion.div
            key={branch.kind}
            // Always visible at the held state (35% opacity) — no scroll-gated
            // invisibility. The staggered highlight animation runs as flair
            // when the section enters viewport.
            initial={reduce ? false : { opacity: 0.35 }}
            whileInView={
              reduce
                ? undefined
                : {
                    opacity: [0.35, 1, 1, 0.35],
                  }
            }
            viewport={{ once: true, margin: "-50px" }}
            transition={{
              duration: dwell + 1.2,
              times: [0, 0.15, 0.15 + dwell / (dwell + 1.2), 1],
              delay: beat,
            }}
            className={`flex items-start gap-2 rounded-lg border ${branch.border} ${branch.bg} p-3`}
          >
            <branch.icon size={16} className={`${branch.color} mt-0.5 flex-shrink-0`} />
            <div className="min-w-0">
              <p className={`text-sm font-semibold ${branch.color}`}>
                {branch.label}
              </p>
              <p className="text-xs text-muted">{branch.plain}</p>
              {isRewrite ? (
                <p className="mt-1 font-mono text-[11px] text-rewrite">
                  rampPercent: 100 → 25
                </p>
              ) : null}
            </div>
          </motion.div>
        );
      })}
    </div>
  );
}

