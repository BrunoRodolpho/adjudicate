// ── Visual atoms ───────────────────────────────────────────────────────

function NodeBox({
  label,
  tone,
  size = "md",
}: {
  label: string;
  tone: "neutral" | "danger";
  size?: "sm" | "md";
}) {
  const padding = size === "sm" ? "px-2 py-1.5 text-[11px]" : "px-3 py-2 text-xs";
  const cls =
    tone === "danger"
      ? "border-refuse/40 bg-refuse/10 text-refuse"
      : "border-edge bg-surface text-ink";
  return (
    <div className={`rounded-md border font-mono ${cls} ${padding}`}>{label}</div>
  );
}

function Arrow({
  tone = "neutral",
  size = "md",
}: {
  tone?: "neutral" | "danger";
  size?: "sm" | "md";
}) {
  const reduce = useReducedMotion();
  const color = tone === "danger" ? "text-refuse/70" : "text-faint";
  const w = size === "sm" ? 18 : 22;
  return (
    <motion.span
      aria-hidden
      animate={reduce ? undefined : { x: [0, 4, 0] }}
      transition={{ duration: 1.6, repeat: Infinity, ease: "easeInOut" }}
      className={color}
    >
      <svg width={w} height={w} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
        <line x1="3" y1="12" x2="21" y2="12" />
        <polyline points="14 6 21 12 14 18" />
      </svg>
    </motion.span>
  );
}

